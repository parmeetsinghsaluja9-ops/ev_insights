// Cleans data/original/superstoreSales.csv -> data/processed/superstore_clean.csv
// + data_quality_report.md/.json. The original file is NEVER modified.
import fs from 'node:fs';
import { readCsv, round } from './lib.js';

const SRC = 'data/original/superstoreSales.csv';
const OUT = 'data/processed/superstore_clean.csv';
const { data, meta } = readCsv(SRC);

const FIXES = { Province: { Saskachewan: 'Saskatchewan' }, Region: { Prarie: 'Prairie' } };
const log = { rowsRead: data.length, corrections: {}, issues: [], dropped: 0 };
const bump = (k, n = 1) => (log.corrections[k] = (log.corrections[k] || 0) + n);

const parseDate = (s) => {
  const m = /^(\d{1,2})\/(\d{1,2})\/(\d{4})$/.exec((s || '').trim());
  if (!m) return null;
  const [, mo, d, y] = m.map(Number);
  const dt = new Date(Date.UTC(y, mo - 1, d));
  if (dt.getUTCMonth() !== mo - 1 || dt.getUTCDate() !== d) return null;
  return dt;
};
const iso = (d) => d.toISOString().slice(0, 10);
const snake = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');

const out = [];
const seen = new Set();
for (const raw of data) {
  const r = {};
  for (const k of meta.fields) r[k] = (raw[k] ?? '').toString().trim();
  for (const [col, map] of Object.entries(FIXES)) {
    if (map[r[col]]) { r[col] = map[r[col]]; bump(`${col}: typo corrected`); }
  }
  const od = parseDate(r['Order Date']), sd = parseDate(r['Ship Date']);
  const nums = ['Sales', 'Profit', 'Order Quantity', 'Discount', 'Shipping Cost', 'Unit Price'].map((c) => Number(r[c]));
  if (!od || !sd || nums.some(Number.isNaN)) { log.dropped++; log.issues.push(`Row ${r['Row ID']}: unparseable date/number`); continue; }
  if (seen.has(r['Row ID'])) { log.dropped++; log.issues.push(`Row ${r['Row ID']}: duplicate Row ID`); continue; }
  seen.add(r['Row ID']);
  const shipDays = Math.round((sd - od) / 864e5);
  if (shipDays < 0) log.issues.push(`Row ${r['Row ID']}: ship date before order date`);
  if (Number(r.Discount) < 0 || Number(r.Discount) > 1) log.issues.push(`Row ${r['Row ID']}: discount out of [0,1]`);
  if (r['Product Base Margin'] === '') bump('Product Base Margin: blank kept as empty (not imputed)');
  const o = {};
  for (const k of meta.fields) o[snake(k)] = r[k];
  o.order_date = iso(od); o.ship_date = iso(sd);
  o.order_year = od.getUTCFullYear();
  o.order_month = od.getUTCMonth() + 1;
  o.order_quarter = `Q${Math.floor(od.getUTCMonth() / 3) + 1}`;
  o.ship_days = shipDays;
  o.profit_margin = Number(r.Sales) ? round(Number(r.Profit) / Number(r.Sales), 4) : '';
  o.is_loss = Number(r.Profit) < 0 ? 1 : 0;
  out.push(o);
}

const cols = Object.keys(out[0]);
const esc = (v) => { v = String(v ?? ''); return /[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v; };
fs.writeFileSync(OUT, [cols.join(','), ...out.map((o) => cols.map((c) => esc(o[c])).join(','))].join('\n') + '\n');

const num = (c) => out.map((o) => Number(o[c]));
const sum = (a) => a.reduce((x, y) => x + y, 0);
const years = [...new Set(out.map((o) => o.order_year))].sort();
const q = {
  ...log, rowsWritten: out.length, columns: cols.length, years,
  dateRange: [out.map((o) => o.order_date).sort()[0], out.map((o) => o.order_date).sort().at(-1)],
  totalSales: round(sum(num('sales'))), totalProfit: round(sum(num('profit'))),
  lossLines: sum(num('is_loss')), maxShipDays: Math.max(...num('ship_days')),
  uniqueOrders: new Set(out.map((o) => o.order_id)).size,
};
fs.writeFileSync('data/processed/data_quality_report.json', JSON.stringify(q, null, 2));

const md = `# Data Quality Report

Generated by \`scripts/clean_data.js\` on actual data (source: \`${SRC}\`, unchanged).

| Check | Result |
|---|---|
| Rows read (after dropping blank trailing line) | ${q.rowsRead} |
| Rows written to cleaned file | ${q.rowsWritten} |
| Rows dropped | ${q.dropped} |
| Columns (original 21 + 7 derived) | ${q.columns} |
| Order date range | ${q.dateRange[0]} to ${q.dateRange[1]} |
| Unique Order IDs | ${q.uniqueOrders} |
| Total Sales / Profit | ${q.totalSales.toLocaleString('en-US')} / ${q.totalProfit.toLocaleString('en-US')} |
| Loss-making order lines (Profit < 0) | ${q.lossLines} |
| Max shipping days | ${q.maxShipDays} |

## Cleaning actions
${Object.entries(q.corrections).map(([k, v]) => `- ${k}: ${v} rows`).join('\n') || '- none'}
- Source file used CR-only line endings and a trailing blank record; normalised on read.
- Dates converted from MM/DD/YYYY to ISO YYYY-MM-DD.
- Whitespace trimmed on all fields.

## Validation issues
${q.issues.length ? q.issues.slice(0, 50).map((i) => `- ${i}`).join('\n') : '- None found (unique Row ID, valid dates, numeric fields, discount in [0,1], ship date >= order date).'}

## Observations / caveats
- "Region" mixes true regions (Atlantic, Ontario, Quebec, Prairie, West) with territory-level values (Nunavut, Northwest Territories, Yukon); kept as supplied.
- Product Base Margin is blank for some rows; not used in KPIs.
- Rows are order *lines*, not orders; use distinct Order ID for order counts.
`;
fs.writeFileSync('data/processed/data_quality_report.md', md);
console.log(JSON.stringify({ read: q.rowsRead, written: q.rowsWritten, dropped: q.dropped, issues: q.issues.length, corrections: q.corrections }, null, 1));
