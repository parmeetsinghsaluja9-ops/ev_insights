// Generates assets/js/data.js (plain script, works from file:// and GitHub Pages) from outputs/analysis.json.
import fs from 'node:fs';
import { DICTIONARY } from './data_dictionary.js';
const A = JSON.parse(fs.readFileSync('outputs/analysis.json', 'utf8'));
const q = JSON.parse(fs.readFileSync('data/processed/data_quality_report.json', 'utf8'));
const pick = (a) => a.map(({ key, sales, profit, margin, lines }) => ({ key: String(key), sales, profit, margin, lines }));
const data = {
  kpis: A.kpis, quality: { rows: q.rowsWritten, dropped: q.dropped, dateRange: q.dateRange },
  byYear: pick(A.byYear), byRegion: pick(A.byRegion), byCategory: pick(A.byCategory),
  bySubCategory: pick(A.bySubCategory).map((x) => ({ ...x, key: x.key.split(' | ')[1] })),
  byShipMode: pick(A.byShipMode), byDiscountBand: pick(A.byDiscountBand), bySegment: pick(A.bySegment),
  dictionary: DICTIONARY,
};
fs.writeFileSync('assets/js/data.js', `/* AUTO-GENERATED by scripts/build_site_data.js - do not edit */\nwindow.SITE_DATA = ${JSON.stringify(data)};\n`);
console.log('assets/js/data.js written');
