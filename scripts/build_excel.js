// Builds excel/tableau_analysis.xlsx with ExcelJS. Formulas carry cached results computed in JS.
import ExcelJS from 'exceljs';
import fs from 'node:fs';
import { loadClean, readCsv } from './lib.js';
import { DICTIONARY } from './data_dictionary.js';

const A = JSON.parse(fs.readFileSync('outputs/analysis.json', 'utf8'));
const { data: clean, meta } = readCsv('data/processed/superstore_clean.csv');
const N = clean.length + 1; // last data row on 'Cleaned Data'
const col = (name) => { const i = meta.fields.indexOf(name); let n = i + 1, s = ''; while (n) { s = String.fromCharCode(65 + ((n - 1) % 26)) + s; n = Math.floor((n - 1) / 26); } return s; };
const rng = (name) => `'Cleaned Data'!$${col(name)}$2:$${col(name)}$${N}`;
const wb = new ExcelJS.Workbook(); wb.creator = 'Tableau vocational project';
const HEAD = { font: { bold: true, color: { argb: 'FFFFFFFF' } }, fill: { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1F4E79' } } };
const head = (ws, row = 1) => { ws.getRow(row).eachCell((c) => Object.assign(c, HEAD)); ws.getRow(row).alignment = { vertical: 'middle', wrapText: true }; };
const MONEY = '#,##0;[Red]-#,##0', PCT = '0.0%';

// 1 Read Me
const rm = wb.addWorksheet('Read Me');
rm.columns = [{ width: 28 }, { width: 100 }];
[['Project', 'Superstore Sales and Profitability Analysis (Tableau vocational training project)'],
 ['Source data', 'curran/data superstoreSales.csv (GitHub), 8,399 order lines, 2009-2012. Original kept unchanged in data/original/.'],
 ['Cleaned data', 'Sheet "Cleaned Data" = data/processed/superstore_clean.csv (generated by scripts/clean_data.js).'],
 ['Formulas', 'KPI, Sales, Profit and Regional sheets use SUMIFS/COUNTIFS over Cleaned Data. Distinct Order/Customer counts are static values from scripts/analyze_data.js (marked).'],
 ['Charts', 'ExcelJS cannot create native Excel charts; data bars are used instead. Real charts belong in Tableau.'],
 ['Performance sheets', '"Performance Testing" is the experiment design. "Test Results" is EMPTY/PENDING until you measure in Tableau. No results are invented.'],
 ['Regenerate', 'npm run clean && npm run analyze && npm run excel'],
 ['Currency', 'Not stated by the source dataset; reported as plain amounts.']].forEach((r) => rm.addRow(r));
rm.getColumn(1).font = { bold: true }; rm.getColumn(2).alignment = { wrapText: true };

// 2 Data Dictionary
const dd = wb.addWorksheet('Data Dictionary');
dd.addRow(['Field (cleaned file)', 'Original name', 'Type', 'Status', 'Description']); head(dd);
DICTIONARY.forEach((r) => dd.addRow(r));
[24, 22, 14, 12, 70].forEach((w, i) => (dd.getColumn(i + 1).width = w));

// 3 Cleaned Data (as table)
const cd = wb.addWorksheet('Cleaned Data', { views: [{ state: 'frozen', ySplit: 1 }] });
const numeric = new Set(['row_id', 'order_id', 'order_quantity', 'sales', 'discount', 'profit', 'unit_price', 'shipping_cost', 'product_base_margin', 'order_year', 'order_month', 'ship_days', 'profit_margin', 'is_loss']);
cd.addTable({ name: 'CleanData', ref: 'A1', headerRow: true, style: { theme: 'TableStyleMedium2', showRowStripes: true },
  columns: meta.fields.map((f) => ({ name: f, filterButton: true })),
  rows: clean.map((r) => meta.fields.map((f) => (numeric.has(f) ? (r[f] === '' ? null : Number(r[f])) : r[f]))) });
meta.fields.forEach((f, i) => (cd.getColumn(i + 1).width = Math.max(12, Math.min(34, f.length + 4))));

// helpers for formula sheets
const sumifs = (v, k, cell) => `SUMIFS(${rng(v)},${rng(k)},${cell})`;
const table = (ws, startRow, title, keyField, keyHeader, items, valueFn = (i) => i.key) => {
  ws.getCell(startRow, 1).value = title; ws.getCell(startRow, 1).font = { bold: true, size: 13 };
  const h = startRow + 1;
  ['' + keyHeader, 'Sales', 'Profit', 'Margin', 'Order lines'].forEach((t, i) => (ws.getCell(h, i + 1).value = t));
  head(ws, h);
  items.forEach((it, i) => {
    const r = h + 1 + i, k = `$A${r}`;
    ws.getCell(r, 1).value = valueFn(it);
    ws.getCell(r, 2).value = { formula: sumifs('sales', keyField, k), result: it.sales };
    ws.getCell(r, 3).value = { formula: sumifs('profit', keyField, k), result: it.profit };
    ws.getCell(r, 4).value = { formula: `IF(B${r}=0,0,C${r}/B${r})`, result: it.margin };
    ws.getCell(r, 5).value = { formula: `COUNTIFS(${rng(keyField)},${k})`, result: it.lines };
    ws.getCell(r, 2).numFmt = MONEY; ws.getCell(r, 3).numFmt = MONEY; ws.getCell(r, 4).numFmt = PCT; ws.getCell(r, 5).numFmt = '#,##0';
  });
  const first = h + 1, last = h + items.length;
  ws.addConditionalFormatting({ ref: `B${first}:B${last}`, rules: [{ type: 'dataBar', cfvo: [{ type: 'min' }, { type: 'max' }], color: { argb: 'FF5B9BD5' } }] });
  ws.addConditionalFormatting({ ref: `D${first}:D${last}`, rules: [{ type: 'cellIs', operator: 'lessThan', formulae: ['0'], style: { font: { color: { argb: 'FFC00000' }, bold: true } } }] });
  return last + 2;
};
const widths = (ws) => [34, 16, 16, 12, 14].forEach((w, i) => (ws.getColumn(i + 1).width = w));

// 4 KPI Summary
const k = wb.addWorksheet('KPI Summary'); widths(k);
k.addRow(['KPI', 'Value', 'Definition', '', '']); head(k);
const kp = A.kpis;
const kpiRows = [
  ['Total Sales', { formula: `SUM(${rng('sales')})`, result: kp.totalSales }, MONEY, 'Sum of Sales'],
  ['Total Profit', { formula: `SUM(${rng('profit')})`, result: kp.totalProfit }, MONEY, 'Sum of Profit'],
  ['Profit Margin', { formula: 'B3/B2', result: kp.margin }, PCT, 'Total Profit / Total Sales'],
  ['Order lines', { formula: `COUNTA(${rng('row_id')})`, result: kp.orderLines }, '#,##0', 'Rows in dataset'],
  ['Distinct orders (static)', kp.orders, '#,##0', 'Distinct Order ID, computed by script'],
  ['Distinct customers (static)', kp.customers, '#,##0', 'Distinct Customer Name, computed by script'],
  ['Avg Order Value', { formula: 'B2/B6', result: kp.avgOrderValue }, MONEY, 'Total Sales / distinct orders'],
  ['Loss-making lines', { formula: `SUM(${rng('is_loss')})`, result: kp.lossLines }, '#,##0', 'Lines with Profit < 0'],
  ['Loss-line share', { formula: 'B9/B5', result: kp.lossLineShare }, PCT, 'Loss lines / all lines'],
  ['Total losses on loss lines', { formula: `SUMIFS(${rng('profit')},${rng('is_loss')},1)`, result: kp.lossTotal }, MONEY, 'Sum of negative profit'],
  ['Avg shipping days', { formula: `AVERAGE(${rng('ship_days')})`, result: kp.avgShipDays }, '0.00', 'Mean ship date - order date'],
];
kpiRows.forEach(([n, v, f, d]) => { const r = k.addRow([n, v, d]); r.getCell(2).numFmt = f; });
k.getColumn(3).width = 46;

// 5 Sales Analysis
const s = wb.addWorksheet('Sales Analysis'); widths(s);
let r0 = table(s, 1, 'Sales by Year', 'order_year', 'Year', A.byYear, (i) => Number(i.key));
r0 = table(s, r0, 'Sales by Category', 'product_category', 'Category', A.byCategory);
r0 = table(s, r0, 'Sales by Customer Segment', 'customer_segment', 'Segment', A.bySegment);
table(s, r0, 'Sales by Ship Mode', 'ship_mode', 'Ship Mode', A.byShipMode);

// 6 Profit Analysis
const p = wb.addWorksheet('Profit Analysis'); widths(p);
r0 = table(p, 1, 'Profit by Sub-Category', 'product_sub_category', 'Sub-Category',
  [...A.bySubCategory].map((x) => ({ ...x, key: x.key.split(' | ')[1] })).sort((a, b) => b.profit - a.profit));
p.getColumn(1).width = 38;
p.getCell(r0, 1).value = 'Discount band analysis (static, from scripts/analyze_data.js)'; p.getCell(r0, 1).font = { bold: true, size: 13 };
['Discount band', 'Sales', 'Profit', 'Margin', 'Order lines'].forEach((t, i) => (p.getCell(r0 + 1, i + 1).value = t)); head(p, r0 + 1);
A.byDiscountBand.forEach((b, i) => { const r = r0 + 2 + i; [b.key, b.sales, b.profit, b.margin, b.lines].forEach((v, j) => (p.getCell(r, j + 1).value = v)); p.getCell(r, 2).numFmt = MONEY; p.getCell(r, 3).numFmt = MONEY; p.getCell(r, 4).numFmt = PCT; });

// 7 Regional Analysis
const g = wb.addWorksheet('Regional Analysis'); widths(g);
r0 = table(g, 1, 'Sales and Profit by Region', 'region', 'Region', A.byRegion);
table(g, r0, 'Sales and Profit by Province', 'province', 'Province', A.byProvince);

// 8 Performance Testing (design)
const pt = wb.addWorksheet('Performance Testing');
pt.addRow(['Test ID', 'Factor', 'Independent variable', 'Levels', 'Controlled variables', 'Metric']); head(pt);
[['T1', 'Amount of data rendered', 'Row count in extract', '2,000 / 4,000 / 8,399 (+ optional 25,000 / 100,000 synthetic-by-replication)', 'Same dashboard, same filters, same device/browser', 'Load time (s), first render'],
 ['T2', 'Utilization of filters', 'Number of active quick filters', '0 / 2 / 4 / 6; plus context vs normal filter', 'Same data, same charts', 'Filter response time (s)'],
 ['T3', 'Number of calculated fields', 'Calculated fields used on sheets', '0 / 3 / 6 / 10 (mix of row-level and LOD)', 'Same data, same layout', 'Load time (s)'],
 ['T4', 'Number of visualizations', 'Worksheets on dashboard', '1 / 3 / 6 / 9', 'Same data, same filters', 'Load time (s)']].forEach((r) => pt.addRow(r));
[8, 26, 28, 60, 40, 26].forEach((w, i) => (pt.getColumn(i + 1).width = w)); pt.eachRow((r) => (r.alignment = { wrapText: true, vertical: 'top' }));

// 9 Test Results (EMPTY on purpose)
const tr = wb.addWorksheet('Test Results');
tr.addRow(['Test ID', 'Level', 'Run 1 (s)', 'Run 2 (s)', 'Run 3 (s)', 'Mean (s)', 'Status', 'Notes']); head(tr);
const levels = { T1: ['2,000 rows', '4,000 rows', '8,399 rows'], T2: ['0 filters', '2 filters', '4 filters', '6 filters'], T3: ['0 calcs', '3 calcs', '6 calcs', '10 calcs'], T4: ['1 viz', '3 viz', '6 viz', '9 viz'] };
let rr = 2;
for (const [id, ls] of Object.entries(levels)) for (const l of ls) { tr.addRow([id, l, null, null, null, { formula: `IF(COUNT(C${rr}:E${rr})=0,"",AVERAGE(C${rr}:E${rr}))` }, 'PENDING - not yet measured', '']); tr.getCell(rr, 6).numFmt = '0.00'; rr++; }
[8, 16, 12, 12, 12, 12, 28, 40].forEach((w, i) => (tr.getColumn(i + 1).width = w));

fs.mkdirSync('excel', { recursive: true });
await wb.xlsx.writeFile('excel/tableau_analysis.xlsx');
console.log('written', wb.worksheets.map((w) => w.name).join(', '));
